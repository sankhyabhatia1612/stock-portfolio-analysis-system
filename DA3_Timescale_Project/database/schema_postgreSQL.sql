-- ============================================================
-- SCHEMA DEFINITION: Stock Portfolio Analysis & Tracking System
-- Database: PostgreSQL + TimescaleDB
-- ============================================================

-- Enable TimescaleDB Extension
CREATE EXTENSION IF NOT EXISTS timescaledb;

CREATE TABLE APP_USER (
    USER_ID VARCHAR(10) PRIMARY KEY,
    FNAME VARCHAR(30) NOT NULL,
    MNAME VARCHAR(30),
    LNAME VARCHAR(30) NOT NULL,
    DOB DATE NOT NULL,
    EMAIL VARCHAR(100) NOT NULL UNIQUE,
    PASSWORD_HASH VARCHAR(255) NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    USER_STATUS VARCHAR(15) DEFAULT 'ACTIVE'
);

CREATE TABLE INVESTOR (
    USER_ID VARCHAR(10) PRIMARY KEY,
    RISK_PROFILE VARCHAR(20),
    FOREIGN KEY (USER_ID) REFERENCES APP_USER(USER_ID) ON DELETE CASCADE
);

CREATE TABLE ADVISOR (
    ADVISOR_ID VARCHAR(10) PRIMARY KEY,
    USER_ID VARCHAR(10) NOT NULL,
    EXPERTISE VARCHAR(100),
    FOREIGN KEY (USER_ID) REFERENCES APP_USER(USER_ID) ON DELETE CASCADE
);

CREATE TABLE ADMIN (
    ADMIN_ID VARCHAR(10) PRIMARY KEY,
    USER_ID VARCHAR(10) NOT NULL,
    PERMISSIONS VARCHAR(500),
    FOREIGN KEY (USER_ID) REFERENCES APP_USER(USER_ID) ON DELETE CASCADE
);

CREATE TABLE CLIENT (
    CLIENT_ID VARCHAR(10) PRIMARY KEY,
    CLIENT_NAME VARCHAR(100) NOT NULL
);

CREATE TABLE INDIVIDUAL (
    IND_ID VARCHAR(10) PRIMARY KEY,
    CLIENT_ID VARCHAR(10) NOT NULL,
    FOREIGN KEY (CLIENT_ID) REFERENCES CLIENT(CLIENT_ID) ON DELETE CASCADE
);

CREATE TABLE INSTITUTIONAL (
    INS_ID VARCHAR(10) PRIMARY KEY,
    CLIENT_ID VARCHAR(10) NOT NULL,
    FOREIGN KEY (CLIENT_ID) REFERENCES CLIENT(CLIENT_ID) ON DELETE CASCADE
);

CREATE TABLE PORTFOLIO (
    PORTFOLIO_ID VARCHAR(10) PRIMARY KEY,
    USER_ID VARCHAR(10) NOT NULL,
    PORTFOLIO_NAME VARCHAR(50) NOT NULL,
    CASH_BALANCE NUMERIC(15,2) DEFAULT 0.00 NOT NULL,
    FOREIGN KEY (USER_ID) REFERENCES APP_USER(USER_ID) ON DELETE CASCADE
);

CREATE TABLE STOCK (
    STOCK_ID VARCHAR(10) PRIMARY KEY,
    STOCK_SYMBOL VARCHAR(20) NOT NULL UNIQUE,
    STOCK_NAME VARCHAR(100) NOT NULL,
    EXCHANGE VARCHAR(20) NOT NULL,
    SECTOR VARCHAR(50),
    CURRENT_PRICE NUMERIC(15,2) NOT NULL,
    LAST_UPDATED TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- Time-Series Table for Stock History
CREATE TABLE STOCK_PRICE_HISTORY (
    PRICE_ID INT NOT NULL,
    STOCK_ID VARCHAR(10) NOT NULL,
    PRICE_DATE TIMESTAMPTZ NOT NULL,
    OPENING_PRICE NUMERIC(15,2),
    CLOSING_PRICE NUMERIC(15,2) NOT NULL,
    HIGH_PRICE NUMERIC(15,2),
    LOW_PRICE NUMERIC(15,2),
    PRIMARY KEY (PRICE_ID, PRICE_DATE),
    FOREIGN KEY (STOCK_ID) REFERENCES STOCK(STOCK_ID) ON DELETE CASCADE
);

